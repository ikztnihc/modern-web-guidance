// Rebuilds skills/modern-web-guidance/INDEX.md from the guide files.
// Run after every upstream sync: node scripts/build-index.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'skills', 'modern-web-guidance');
const guidesDir = join(root, 'guides');

// Guides about a component that shadcn/ui already provides. For these, the shadcn
// component wins: read the guide only for accessibility and behaviour rules.
const SHADCN_OWNED = new Set([
  'accordion', 'breadcrumbs', 'card', 'carousel', 'checkbox', 'dialog', 'hovercard', 'menu',
  'navigation-drawer', 'persistent-toast-notifications', 'progress', 'spinner', 'tabs', 'toolbar',
  'animated-select-picker', 'branded-select-styling', 'custom-select-picker-layouts',
  'select-menu-interaction', 'slider', 'switch', 'sms-otp-form',
  'position-aware-tooltips', 'viewport-aware-dropdowns', 'responsive-table', 'dark-mode-toggle',
  'declarative-dialog-popover-control', 'light-dismiss-a-dialog', 'platform-controls-dismiss-dialog',
  'prevent-page-scroll-under-modal-dialog', 'animate-to-from-top-layer', 'interest-triggered-tooltips',
  'persistent-top-layer-ui',
]);

function summary(text) {
  const lines = text.split('\n');
  const title = (lines.find((l) => l.startsWith('# ')) ?? '').slice(2).trim();
  const para = lines.find((l) => l.trim() && !l.startsWith('#') && !l.startsWith('<!--') && !l.startsWith('```'));
  let first = (para ?? '').replace(/\*\*/g, '').replace(/\s+/g, ' ').trim();
  const dot = first.search(/\.(\s|$)/);
  if (dot > 0) first = first.slice(0, dot + 1);
  if (first.length > 180) first = first.slice(0, 177) + '...';
  return { title, first };
}

let out = '# Guide index\n\nGenerated by `scripts/build-index.mjs`. Do not edit by hand.\n\n';
out += 'Path = `guides/<category>/<id>.md`. **[shadcn]** = shadcn/ui owns this component: keep the shadcn component and use the guide only for accessibility and behaviour rules.\n\n';
let seen = new Set();
for (const cat of readdirSync(guidesDir).sort()) {
  const files = readdirSync(join(guidesDir, cat)).filter((f) => f.endsWith('.md')).sort();
  if (!files.length) continue;
  out += `## ${cat}\n\n`;
  for (const f of files) {
    const id = f.slice(0, -3);
    seen.add(id);
    const { title, first } = summary(readFileSync(join(guidesDir, cat, f), 'utf8'));
    out += `- \`${cat}/${id}\`${SHADCN_OWNED.has(id) ? ' **[shadcn]**' : ''}: ${title}. ${first}\n`;
  }
  out += '\n';
}
const missing = [...SHADCN_OWNED].filter((id) => !seen.has(id));
if (missing.length) {
  console.error('SHADCN_OWNED ids not found (renamed upstream?):', missing.join(', '));
  process.exitCode = 1;
}
writeFileSync(join(root, 'INDEX.md'), out);
console.log(`INDEX.md: ${seen.size} guides`);
